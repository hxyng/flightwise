-- FlightWise Snowflake setup. Idempotent. Run by scripts/load_snowflake.py (or paste into a worksheet;
-- then run the PUT line from SnowSQL / `snow sql`, since PUT is not available in worksheets).
-- UNTESTED: written without a Snowflake account.
CREATE DATABASE IF NOT EXISTS FLIGHTWISE;
CREATE SCHEMA IF NOT EXISTS FLIGHTWISE.PUBLIC;
USE SCHEMA FLIGHTWISE.PUBLIC;

CREATE TABLE IF NOT EXISTS FLIGHTS (
    FL_DATE DATE,
    MONTH INTEGER,
    DAY_OF_WEEK INTEGER,
    CARRIER VARCHAR,
    CARRIER_NAME VARCHAR,
    FLIGHT_NUM INTEGER,
    ORIGIN VARCHAR,
    ORIGIN_CITY VARCHAR,
    DEST VARCHAR,
    DEST_CITY VARCHAR,
    CRS_DEP_TIME INTEGER,
    DEP_HOUR INTEGER,
    DEP_DELAY FLOAT,
    DEP_DEL15 INTEGER,
    ARR_DELAY FLOAT,
    ARR_DEL15 INTEGER,
    CANCELLED INTEGER,
    CANCELLATION_CODE VARCHAR,
    DISTANCE FLOAT,
    CARRIER_DELAY FLOAT,
    WEATHER_DELAY FLOAT,
    NAS_DELAY FLOAT,
    LATE_AIRCRAFT_DELAY FLOAT
);

CREATE FILE FORMAT IF NOT EXISTS FLIGHTS_CSV
    TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL') COMPRESSION = GZIP EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS FLIGHTS_STAGE FILE_FORMAT = FLIGHTS_CSV;

