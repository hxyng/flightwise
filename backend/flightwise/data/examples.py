"""Few-shot question -> SQL pairs. All use the common subset of DuckDB and Snowflake SQL."""
from __future__ import annotations

EXAMPLES: list[tuple[str, str]] = [
    ("What is the best hour to fly out of OKC?",
     "SELECT DEP_HOUR, ROUND(100.0 * AVG(DEP_DEL15), 1) AS PCT_DELAYED, COUNT(*) AS FLIGHTS "
     "FROM FLIGHTS WHERE ORIGIN = 'OKC' GROUP BY DEP_HOUR HAVING COUNT(*) >= 30 ORDER BY DEP_HOUR"),
    ("Which airline is the most reliable?",
     "SELECT CARRIER_NAME, ROUND(100.0 * AVG(DEP_DEL15), 1) AS PCT_DELAYED, "
     "ROUND(100.0 * AVG(CANCELLED), 2) AS PCT_CANCELLED, COUNT(*) AS FLIGHTS "
     "FROM FLIGHTS GROUP BY CARRIER_NAME HAVING COUNT(*) >= 1000 ORDER BY PCT_DELAYED ASC"),
    ("How do delays change by day of the week?",
     "SELECT DAY_OF_WEEK, ROUND(AVG(DEP_DELAY), 1) AS AVG_DEP_DELAY, "
     "ROUND(100.0 * AVG(DEP_DEL15), 1) AS PCT_DELAYED FROM FLIGHTS GROUP BY DAY_OF_WEEK ORDER BY DAY_OF_WEEK"),
    ("What are the worst routes for delays?",
     "SELECT ORIGIN || '-' || DEST AS ROUTE, ROUND(100.0 * AVG(DEP_DEL15), 1) AS PCT_DELAYED, COUNT(*) AS FLIGHTS "
     "FROM FLIGHTS GROUP BY ORIGIN || '-' || DEST HAVING COUNT(*) >= 200 ORDER BY PCT_DELAYED DESC LIMIT 10"),
    ("How many flights are cancelled each month?",
     "SELECT MONTH, SUM(CANCELLED) AS CANCELLED_FLIGHTS, ROUND(100.0 * AVG(CANCELLED), 2) AS PCT_CANCELLED "
     "FROM FLIGHTS GROUP BY MONTH ORDER BY MONTH"),
    ("What causes delays at DFW?",
     "SELECT 'Airline' AS CAUSE, ROUND(SUM(CARRIER_DELAY)) AS TOTAL_MINUTES FROM FLIGHTS WHERE ORIGIN = 'DFW' "
     "UNION ALL SELECT 'Weather', ROUND(SUM(WEATHER_DELAY)) FROM FLIGHTS WHERE ORIGIN = 'DFW' "
     "UNION ALL SELECT 'Air traffic system', ROUND(SUM(NAS_DELAY)) FROM FLIGHTS WHERE ORIGIN = 'DFW' "
     "UNION ALL SELECT 'Late aircraft', ROUND(SUM(LATE_AIRCRAFT_DELAY)) FROM FLIGHTS WHERE ORIGIN = 'DFW' "
     "ORDER BY TOTAL_MINUTES DESC"),
    ("What is the delay risk for American Airlines leaving DFW at 5pm?",
     "SELECT COUNT(*) AS FLIGHTS, ROUND(100.0 * AVG(DEP_DEL15), 1) AS PCT_DELAYED, "
     "ROUND(AVG(DEP_DELAY), 1) AS AVG_DEP_DELAY, ROUND(100.0 * AVG(CANCELLED), 2) AS PCT_CANCELLED "
     "FROM FLIGHTS WHERE CARRIER = 'AA' AND ORIGIN = 'DFW' AND DEP_HOUR = 17"),
    ("Show the daily delay rate for Delta in July.",
     "SELECT FL_DATE, ROUND(100.0 * AVG(DEP_DEL15), 1) AS PCT_DELAYED FROM FLIGHTS "
     "WHERE CARRIER = 'DL' AND MONTH = 7 GROUP BY FL_DATE ORDER BY FL_DATE"),
]
